export function getCurrentSolarTerm(dateStr) {
  const d = new Date(dateStr);
  let cur = SOLAR_TERMS_2026[SOLAR_TERMS_2026.length - 1];
  for (let i = 0; i < SOLAR_TERMS_2026.length; i++) {
    if (d >= new Date(SOLAR_TERMS_2026[i].date)) cur = SOLAR_TERMS_2026[i];
  }
  return cur;
}
